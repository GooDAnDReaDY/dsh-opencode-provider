import { writeFile } from 'node:fs/promises'
import path from 'node:path'

const PROVIDER = 'opencode-go'
const SOURCE = 'https://models.dev/api.json'
const OUTPUT = path.resolve('src/models.generated.ts')

const response = await fetch(SOURCE)
if (!response.ok) throw new Error(`models.dev returned ${response.status}`)
const catalog = await response.json()
const provider = catalog[PROVIDER]
if (!provider?.models) throw new Error(`provider ${PROVIDER} is missing from models.dev`)

const TRANSPORTS = {
  '@ai-sdk/openai': 'openai-responses',
  '@ai-sdk/openai-compatible': 'openai-chat',
  '@ai-sdk/anthropic': 'anthropic',
  '@ai-sdk/google': 'google',
}

const LADDER = ['off', 'minimal', 'low', 'medium', 'high', 'xhigh', 'max']

function transportOf(model) {
  const npm = model.provider?.npm
  if (npm && TRANSPORTS[npm]) return TRANSPORTS[npm]
  const api = String(model.provider?.api ?? '')
  if (api.includes('/anthropic/')) return 'anthropic'
  if (api.includes('/google/')) return 'google'
  if (api.includes('/openai/')) return 'openai-chat'
  return 'openai-chat'
}

function reasoningOf(model) {
  if (!model.reasoning) return []
  const options = Array.isArray(model.reasoning_options) ? model.reasoning_options : []
  for (const option of options) {
    if (option?.type === 'effort' && Array.isArray(option.values)) {
      return LADDER.filter((level) => option.values.includes(level))
    }
  }
  if (options.some((option) => option?.type === 'toggle')) return ['off', 'low', 'medium', 'high']
  return ['off', 'low', 'medium', 'high']
}

const models = Object.values(provider.models)
  .map((model) => {
    const input = Array.isArray(model.modalities?.input) && model.modalities.input.includes('image')
      ? ['text', 'image']
      : ['text']
    const cost = model.cost ?? {}
    return {
      id: model.id,
      name: model.name ?? model.id,
      transport: transportOf(model),
      contextWindow: Number(model.limit?.context) || 262144,
      maxTokens: Number(model.limit?.output) || 32768,
      input,
      reasoning: reasoningOf(model),
      free: model.id.endsWith('-free') || (Number(cost.input) === 0 && Number(cost.output) === 0),
      cost: {
        input: Number(cost.input) || 0,
        output: Number(cost.output) || 0,
        cacheRead: Number(cost.cache_read) || 0,
      },
    }
  })
  .sort((a, b) => a.id.localeCompare(b.id))

const body = `// Generated by scripts/sync-models.mjs from ${SOURCE}.
// Do not edit by hand.

export type OpenCodeTransport = 'openai-chat' | 'openai-responses' | 'anthropic' | 'google'

export interface OpenCodeModelMeta {
  readonly id: string
  readonly name: string
  readonly transport: OpenCodeTransport
  readonly contextWindow: number
  readonly maxTokens: number
  readonly input: readonly ('text' | 'image')[]
  readonly reasoning: readonly string[]
  readonly free: boolean
  readonly cost: { readonly input: number; readonly output: number; readonly cacheRead: number }
}

export const GENERATED_MODELS: Record<string, OpenCodeModelMeta> = ${JSON.stringify(
  Object.fromEntries(models.map((model) => [model.id, model])),
  null,
  2,
)}
`

await writeFile(OUTPUT, body, 'utf8')
console.log(`wrote ${models.length} models to ${OUTPUT}`)
